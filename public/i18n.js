window.currentLanguage = localStorage.getItem("unirank_language") || "en";

window.setLanguage = function(lang) {
  if (!["tr", "en"].includes(lang)) return;

  window.currentLanguage = lang;
  localStorage.setItem("unirank_language", lang);
  document.documentElement.lang = lang;

  window.applyTranslations();
  window.updateLanguageToggleUI();

  if (typeof window.renderCountryFilter === "function") window.renderCountryFilter();
  if (typeof window.renderCategoryUI === "function") window.renderCategoryUI();
  if (typeof window.populateProfileInterestOptions === "function") window.populateProfileInterestOptions();
  if (typeof window.processAndRender === "function") window.processAndRender();
};

window.updateLanguageToggleUI = function() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === window.currentLanguage);
    button.setAttribute("aria-pressed", button.dataset.lang === window.currentLanguage ? "true" : "false");
  });
};

window.t = function(key) {
  return I18N[window.currentLanguage]?.[key] || I18N.en?.[key] || key;
};

window.localizedValue = function(value) {
  if (value == null) return "";
  if (typeof value === "string") return value;
  if (typeof value === "object") {
    return value[window.currentLanguage] || value.en || value.tr || "";
  }
  return String(value);
};

window.localizedArray = function(values) {
  if (!Array.isArray(values)) return [];
  return values.map(window.localizedValue).filter(Boolean);
};

window.formatRisk = function(value) {
  return window.t(`risk_${value || "unknown"}`);
};

window.formatConfidence = function(value) {
  return window.t(`confidence_${value || "unknown"}`);
};

window.getCountryName = function(countryKey) {
  if (!countryKey) return "";
  const obj = window.COUNTRY_LABELS[countryKey];
  if (obj) {
      return obj[window.currentLanguage] || obj.en || countryKey;
  }
  return countryKey;
};

window.applyTranslations = function() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = window.t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = window.t(key);
  });
  
  // Dispatch custom event for dynamic components to re-render
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: window.currentLanguage }}));
};

// Initialize toggle UI on load
document.addEventListener("DOMContentLoaded", () => {
    window.updateLanguageToggleUI();
});


